/**
 * The WHO Child Growth Standards (2006) as LMS values, 0 to 60 months, and the
 * z-score that goes with them. Pure: no database, no clock.
 *
 * Source: the WHO anthro package (github.com/WorldHealthOrganization/anthro,
 * data-raw/growthstandards weianthro.txt and lenanthro.txt), which holds one
 * row per day of age; kept here at each whole month (day round(m * 30.4375))
 * and interpolated linearly between months. Length (lying) to 24 months,
 * height (standing) after, as the standard itself switches.
 *
 * z = ((X / M) ** L - 1) / (L * S), and for weight beyond ±3 the WHO's
 * restricted method (the distance past SD3 measured in SD2-SD3 steps), so a
 * very small child does not read as impossibly small.
 */
final class WhoGrowth
{
    public const MAX_MONTHS = 60;

    /** Days in an average month, as the WHO tables use. */
    public const DAYS_PER_MONTH = 30.4375;

    /** Weight-for-age z-score, or null outside 0-60 months. */
    public static function weightForAge(float $kg, int $ageDays, bool $male): ?float
    {
        $lms = self::lms($male ? self::WEIGHT_MALE : self::WEIGHT_FEMALE, $ageDays);

        return $lms === null || $kg <= 0 ? null : self::restricted($kg, ...$lms);
    }

    /** Length/height-for-age z-score, or null outside 0-60 months. */
    public static function heightForAge(float $cm, int $ageDays, bool $male): ?float
    {
        $lms = self::lms($male ? self::LENGTH_MALE : self::LENGTH_FEMALE, $ageDays);

        return $lms === null || $cm <= 0 ? null : self::z($cm, ...$lms);
    }

    /** The weight in kg at a z-score and an age (a reference line on the chart). */
    public static function weightAt(float $z, int $ageDays, bool $male): ?float
    {
        $lms = self::lms($male ? self::WEIGHT_MALE : self::WEIGHT_FEMALE, $ageDays);
        if ($lms === null) {
            return null;
        }
        [$l, $m, $s] = $lms;

        return $m * (1 + $l * $s * $z) ** (1 / $l);
    }

    /** The length/height in cm at a z-score and an age. */
    public static function heightAt(float $z, int $ageDays, bool $male): ?float
    {
        $lms = self::lms($male ? self::LENGTH_MALE : self::LENGTH_FEMALE, $ageDays);

        return $lms === null ? null : $lms[1] * (1 + $lms[2] * $z);
    }

    /**
     * @param  array<int, array{0:float,1:float,2:float}>  $table
     * @return array{0:float,1:float,2:float}|null
     */
    private static function lms(array $table, int $ageDays): ?array
    {
        if ($ageDays < 0) {
            return null;
        }
        $months = $ageDays / self::DAYS_PER_MONTH;
        if ($months > self::MAX_MONTHS + 0.5) {
            return null;
        }
        $lo = min((int) floor($months), self::MAX_MONTHS);
        $hi = min($lo + 1, self::MAX_MONTHS);
        $t = $hi === $lo ? 0.0 : $months - $lo;

        return [
            $table[$lo][0] + ($table[$hi][0] - $table[$lo][0]) * $t,
            $table[$lo][1] + ($table[$hi][1] - $table[$lo][1]) * $t,
            $table[$lo][2] + ($table[$hi][2] - $table[$lo][2]) * $t,
        ];
    }

    private static function z(float $x, float $l, float $m, float $s): float
    {
        return abs($l) < 1e-9 ? log($x / $m) / $s : ((($x / $m) ** $l) - 1) / ($l * $s);
    }

    private static function restricted(float $x, float $l, float $m, float $s): float
    {
        $z = self::z($x, $l, $m, $s);
        $at = fn (float $sd) => $m * (1 + $l * $s * $sd) ** (1 / $l);

        if ($z > 3) {
            return 3 + ($x - $at(3)) / ($at(3) - $at(2));
        }
        if ($z < -3) {
            return -3 + ($x - $at(-3)) / ($at(-2) - $at(-3));
        }

        return $z;
    }

